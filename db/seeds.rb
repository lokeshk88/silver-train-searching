books_by_genre.each do |genre, books|
  books.each do |name, author, year|
    book = Book.find_or_initialize_by(name: name)
    next unless book.new_record?

    book.assign_attributes(genre: genre, year: year, status: true)
    book.save!
    seeded_count += 1
  end
end

